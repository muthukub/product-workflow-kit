"""Generate Claude Code profiles from the canonical Codex specialist prompts."""

import argparse
import json
from pathlib import Path
import re
import sys

try:
    import tomllib
except ImportError:
    try:
        import tomli as tomllib
    except ImportError:
        try:
            from pip._vendor import tomli as tomllib
        except ImportError:
            sys.exit("TOML parser missing: use Python 3.11+ or install tomli.")


ROOT = Path(__file__).resolve().parents[1]


def expected_profiles():
    profiles = []
    for path in sorted((ROOT / ".codex/agents").glob("*.toml")):
        source = tomllib.loads(path.read_text(encoding="utf-8-sig"))
        for field in ("name", "description", "developer_instructions"):
            if not isinstance(source.get(field), str) or not source[field].strip():
                raise ValueError(f"{path.name}: missing nonempty {field}")
        profiles.append(source)
    if not profiles:
        raise ValueError("No canonical Codex profiles found")
    names = {item["name"]: item["name"].replace("_", "-") for item in profiles}
    if len(set(names.values())) != len(profiles):
        raise ValueError("Duplicate agent names after Claude name translation")
    pattern = re.compile(r"\b(?:" + "|".join(map(re.escape, names)) + r")\b")
    result = {}
    for source in profiles:
        name = names[source["name"]]
        if not re.fullmatch(r"[a-z][a-z0-9-]*", name):
            raise ValueError(f"Invalid Claude agent name: {name}")
        prompt = pattern.sub(lambda match: names[match.group()], source["developer_instructions"])
        prompt = prompt.replace("Before writing, read AGENTS.md,",
                                "Before writing, read CLAUDE.md, AGENTS.md,")
        result[name] = (
            "---\n"
            f"name: {name}\n"
            f"description: {json.dumps(source['description'], ensure_ascii=True)}\n"
            "model: inherit\n"
            "---\n\n"
            "<!-- Generated by scripts/sync-claude-agents.py; edit the canonical Codex profile. -->\n\n"
            + prompt.strip() + "\n"
        )
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check drift without writing")
    args = parser.parse_args()
    destination = ROOT / ".claude/agents"
    try:
        expected = expected_profiles()
    except (ValueError, OSError, tomllib.TOMLDecodeError) as exc:
        print(f"FAILED: {exc}")
        return 1
    errors = []
    # Keep user-added files intact; flag unexpected names rather than deleting them.
    for path in destination.glob("*.md"):
        if path.stem not in expected:
            errors.append(f"Unexpected Claude profile: {path.name}; review it manually")
    if not args.check:
        destination.mkdir(parents=True, exist_ok=True)
    for name, content in expected.items():
        path = destination / f"{name}.md"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8-sig") != content:
                errors.append(f"Missing or stale Claude profile: {name}.md")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    if errors:
        print("FAILED:\n" + "\n".join(f"- {error}" for error in errors))
        return 1
    print(f"PASS: {len(expected)} Claude Code profiles "
          + ("match their canonical prompts." if args.check else "generated."))
    return 0


if __name__ == "__main__":
    sys.exit(main())
